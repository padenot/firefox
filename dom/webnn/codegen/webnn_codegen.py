def ipc_enum_traits(output, webidl):
    model = Model(webidl)
    out = [
        MPL,
        "// " + HEADER_NOTE,
        "",
        "#ifndef DOM_WEBNN_WEBNNIPCUTILS_H_",
        "#define DOM_WEBNN_WEBNNIPCUTILS_H_",
        "",
        '#include "mozilla/dom/BindingIPCUtils.h"',
        '#include "mozilla/dom/WebNNBinding.h"',
        "",
        "namespace IPC {",
        "",
    ]
    for enum in model.enums:
        name = "mozilla::dom::" + enum.identifier.name
        out += [
            "template <>",
            "struct ParamTraits<%s>" % name,
            "    : public mozilla::dom::WebIDLEnumSerializer<%s> {};" % name,
            "",
        ]
    out += ["}  // namespace IPC", "", "#endif  // DOM_WEBNN_WEBNNIPCUTILS_H_", ""]
    output.write("\n".join(out))
    return {webidl, __file__}


def method_params(op):
    params = ["%s %s" % (a.type.binding_param(), a.cpp_name) for a in op.args]
    if op.multi_output:
        params.append("nsTArray<RefPtr<MLOperand>>& aRetVal")
    params.append("ErrorResult& aRv")
    return params


def graph_builder_header(output, webidl):
    model = Model(webidl)
    out = [
        MPL,
        "// " + HEADER_NOTE,
        "// Included in the declaration of MLGraphBuilder.",
        "",
    ]
    for op in model.ops:
        ret = "void" if op.multi_output else "already_AddRefed<MLOperand>"
        out.append("%s %s(%s);" % (ret, op.native, ", ".join(method_params(op))))
    out.append("")
    output.write("\n".join(out))
    return {webidl, __file__}


def to_ipc_expr(t, expr, optional):
    """C++ expression converting a binding value to its IPDL representation."""
    if optional:
        if t.kind == "operand":
            return "MLGraphBuilder::OptionalIndex(%s)" % expr
        if t.kind == "sequence":
            return "webnn::ToOptionalArray(%s)" % expr
        return "webnn::ToMaybe(%s)" % expr
    if t.kind == "operand":
        return "%s.Index()" % expr
    if t.kind == "operands":
        return "MLGraphBuilder::Indices(%s)" % expr
    if t.kind == "string":
        return "NS_ConvertUTF16toUTF8(%s)" % expr
    if t.kind == "sequence":
        return "webnn::ToArray(%s)" % expr
    if t.kind in ("dictionary", "union"):
        return "ToIPC(%s)" % expr
    return expr


def operand_checks(op):
    checks = []
    for arg in op.args:
        if arg.type.kind == "operand":
            checks.append("CheckOperand(%s, aRv)" % arg.cpp_name)
        elif arg.type.kind == "operands":
            checks.append("CheckOperands(%s, aRv)" % arg.cpp_name)
    return checks


def dict_operand_checks(d, expr):
    checks = []
    for m in d.members:
        if m.type.kind == "operand":
            checks.append("CheckOperand(%s.m%s, aRv)" % (expr, first_cap(m.name)))
    return checks


def graph_builder_cpp(output, webidl):
    model = Model(webidl)
    dicts = {d.name: d for d in model.dicts}
    out = [
        MPL,
        "// " + HEADER_NOTE,
        "",
        '#include "mozilla/dom/MLGraphBuilder.h"',
        "",
        '#include "mozilla/dom/MLContext.h"',
        '#include "mozilla/webnn/WebNNUtils.h"',
        '#include "mozilla/webnn/WebNNValidation.h"',
        "",
        "namespace mozilla::dom {",
        "",
    ]
    for union in model.unions:
        out.append(
            "static webnn::WebNN%s ToIPC(const %s& aValue) {"
            % (union.union_name(), union.name)
        )
        for m in union.members:
            raw = m.idl.name
            out += [
                "  if (aValue.Is%s()) {" % raw,
                "    return webnn::WebNN%s(%s);"
                % (
                    union.union_name(),
                    to_ipc_expr(m, "aValue.GetAs%s()" % raw, False),
                ),
                "  }",
            ]
        out += ['  MOZ_CRASH("Uninitialized union");', "}", ""]
    for d in model.dicts:
        out.append(
            "static webnn::%s ToIPC(const %s& aValue) {"
            % (ipdl_dict_name(d.name), d.name)
        )
        fields = [
            to_ipc_expr(m.type, "aValue.m%s" % first_cap(m.name), m.optional)
            for m in d.members
        ]
        out.append(
            "  return webnn::%s(%s);" % (ipdl_dict_name(d.name), ", ".join(fields))
        )
        out += ["}", ""]
    for op in model.ops:
        ret = "void" if op.multi_output else "already_AddRefed<MLOperand>"
        fail = "return;" if op.multi_output else "return nullptr;"
        out.append(
            "%s MLGraphBuilder::%s(%s) {"
            % (ret, op.native, ", ".join(method_params(op)))
        )
        checks = ["CheckState(aRv)"] + operand_checks(op)
        for arg in op.args:
            if arg.type.kind == "dictionary":
                checks += dict_operand_checks(dicts[arg.type.name], arg.cpp_name)
        out.append("  if (!%s) {" % " ||\n      !".join(checks))
        out += ["    %s" % fail, "  }"]
        out.append("  nsTArray<webnn::OperandDescriptor> descriptors;")
        call_args = [a.cpp_name for a in op.args] + ["descriptors", "aRv"]
        out.append(
            "  if (!webnn::Validate%s(%s)) {" % (op.native, ", ".join(call_args))
        )
        out += ["    %s" % fail, "  }"]
        out.append(
            "  nsTArray<RefPtr<MLOperand>> outputs = AddOutputs(std::move(descriptors));"
        )
        fields = [to_ipc_expr(a.type, a.cpp_name, False) for a in op.args]
        if op.multi_output:
            fields.append("OutputIndices(outputs)")
        else:
            out.append("  MOZ_RELEASE_ASSERT(outputs.Length() == 1);")
            fields.append("outputs[0]->Index()")
        out.append(
            "  mOperations.AppendElement(webnn::%s(%s));"
            % (op.ipdl_struct, ", ".join(fields))
        )
        if op.multi_output:
            out.append("  aRetVal = std::move(outputs);")
        else:
            out.append("  return outputs[0].forget();")
        out += ["}", ""]
    out += ["}  // namespace mozilla::dom", ""]
    output.write("\n".join(out))
    return {webidl, __file__}


def validator_decl(op):
    params = ["%s %s" % (a.type.validator_param(), a.cpp_name) for a in op.args]
    params += ["nsTArray<OperandDescriptor>& aOutputs", "ErrorResult& aRv"]
    return "bool Validate%s(%s)" % (op.native, ", ".join(params))


