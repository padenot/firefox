# Value types shared by the operators. Rust and C must agree on their layout.
C_PRELUDE = """typedef uint32_t WebnnOperandId;

typedef struct WebnnOptionalOperand {
  bool present;
  WebnnOperandId id;
} WebnnOptionalOperand;

typedef struct WebnnOptionalF64 {
  bool present;
  double value;
} WebnnOptionalF64;

// UTF-8, not null-terminated.
typedef struct WebnnStr {
  const char* data;
  uintptr_t len;
} WebnnStr;
"""

C_SLICES = [
    ("WebnnU32Slice", "uint32_t"),
    ("WebnnF32Slice", "float"),
    ("WebnnOperandSlice", "WebnnOperandId"),
]

RUST_PRELUDE = """#[repr(transparent)]
#[derive(Clone, Copy, Debug)]
pub struct WebnnOperandId(pub u32);

#[repr(C)]
pub struct WebnnOptionalOperand {
    pub present: bool,
    pub id: WebnnOperandId,
}

#[repr(C)]
pub struct WebnnOptionalF64 {
    pub present: bool,
    pub value: f64,
}

#[repr(C)]
pub struct WebnnStr {
    pub data: *const u8,
    pub len: usize,
}

#[repr(C)]
pub struct Slice<T> {
    pub data: *const T,
    pub len: usize,
}

#[repr(C)]
pub struct OptionalSlice<T> {
    pub present: bool,
    pub data: *const T,
    pub len: usize,
}

pub type WebnnU32Slice = Slice<u32>;
pub type WebnnOptionalU32Slice = OptionalSlice<u32>;
pub type WebnnF32Slice = Slice<f32>;
pub type WebnnOptionalF32Slice = OptionalSlice<f32>;
pub type WebnnOperandSlice = Slice<WebnnOperandId>;
"""


def c_slice(name, element, optional):
    if optional:
        name = name.replace("Webnn", "WebnnOptional", 1)
    out = ["typedef struct %s {" % name]
    if optional:
        out.append("  bool present;")
    out += ["  const %s* data;" % element, "  uintptr_t len;", "} %s;" % name, ""]
    return out


def ffi_header(output, webidl):
    model = Model(webidl)
    out = [
        MPL,
        "// " + HEADER_NOTE,
        "// Per-operator part of the webnn_engine FFI, see webnn_ops.rs.",
        "",
        "#ifndef WEBNN_ENGINE_OPS_H_",
        "#define WEBNN_ENGINE_OPS_H_",
        "",
        '#include "mozilla/webnn/webnn_engine.h"',
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        C_PRELUDE,
    ]
    for name, element in C_SLICES:
        out += c_slice(name, element, False)
        if name != "WebnnOperandSlice":
            out += c_slice(name, element, True)
    for enum in model.enums:
        name = ffi_enum_name(enum.identifier.name)
        out.append("typedef uint32_t %s;" % name)
        out.append("enum {")
        for i, v in enumerate(enum.values()):
            out.append("  %s_%s = %d," % (name, rust_variant(v), i))
        out += ["};", ""]
    for e in model.enum_sequences:
        out += c_slice(sequence_ffi_name(e, False), ffi_enum_name(e.name), False)
        out += c_slice(sequence_ffi_name(e, False), ffi_enum_name(e.name), True)
    for union in model.unions:
        name = "Webnn" + union.union_name()
        out.append("typedef struct %s {" % name)
        out.append("  uint32_t tag;")
        for m in union.members:
            out.append("  %s %s;" % (m.ffi_c(), snake(m.union_member_name())))
        out += ["} %s;" % name, ""]
    for d in model.dicts:
        name = ffi_dict_name(d.name)
        out.append("typedef struct %s {" % name)
        for m in d.members:
            out.append("  %s %s;" % (m.type.ffi_c(m.optional), snake(m.name)))
        out += ["} %s;" % name, ""]
    for op in model.ops:
        name = ffi_args_name(op)
        out.append("typedef struct %s {" % name)
        for a in op.args:
            out.append("  %s %s;" % (a.type.ffi_c(), snake(a.name)))
        out += ["} %s;" % name, ""]
    for op in model.ops:
        out.append(
            "WebnnStatus %s(WebnnGraphBuilder* builder, const %s* args, "
            "uint32_t* outputs, uintptr_t outputs_capacity, uintptr_t* outputs_len);"
            % (op.ffi_fn, ffi_args_name(op))
        )
    out += [
        "",
        "#ifdef __cplusplus",
        '}  // extern "C"',
        "#endif",
        "",
        "#define WEBNN_ENGINE_OP_FUNCTION_LIST(X) \\",
    ]
    out += ["  X(%s) \\" % op.ffi_fn for op in model.ops]
    out += ["", "", "#endif  // WEBNN_ENGINE_OPS_H_", ""]
    output.write("\n".join(out))
    return {webidl, __file__}


def ffi_rust(output, webidl):
    model = Model(webidl)
    out = [
        "// " + HEADER_NOTE,
        "// Included by dom/webnn/engine/ops.rs.",
        "",
        RUST_PRELUDE,
    ]
    for enum in model.enums:
        name = ffi_enum_name(enum.identifier.name)
        out += [
            "#[repr(u32)]",
            "#[derive(Clone, Copy, Debug)]",
            "pub enum %s {" % name,
        ]
        for v in enum.values():
            out.append("    %s," % rust_variant(v))
        out += ["}", "", "impl %s {" % name, "    fn as_str(self) -> &'static str {"]
        out.append("        match self {")
        for v in enum.values():
            out.append('            Self::%s => "%s",' % (rust_variant(v), v))
        out += ["        }", "    }", "}", ""]
        out += [
            "impl<T: FromStr> Conv<T> for %s {" % name,
            "    fn conv(&self) -> Result<T, Error> {",
            "        T::from_str(self.as_str()).map_err(|_| Error::Unsupported(self.as_str()))",
            "    }",
            "}",
            "",
        ]
    for e in model.enum_sequences:
        name = ffi_enum_name(e.name)
        out += [
            "pub type %s = Slice<%s>;" % (sequence_ffi_name(e, False), name),
            "pub type %s = OptionalSlice<%s>;" % (sequence_ffi_name(e, True), name),
            "",
        ]
    for union in model.unions:
        name = "Webnn" + union.union_name()
        out += ["#[repr(C)]", "pub struct %s {" % name, "    pub tag: u32,"]
        for m in union.members:
            out.append("    pub %s: %s," % (snake(m.union_member_name()), m.ffi_rust()))
        out += ["}", ""]
    for d in model.dicts:
        name = ffi_dict_name(d.name)
        out += ["#[repr(C)]", "pub struct %s {" % name]
        for m in d.members:
            out.append("    pub %s: %s," % (snake(m.name), m.type.ffi_rust(m.optional)))
        out += ["}", ""]
        out += [
            "impl Conv<%s> for %s {" % (d.name, name),
            "    fn conv(&self) -> Result<%s, Error> {" % d.name,
            "        Ok(%s {" % d.name,
        ]
        for m in d.members:
            out.append(
                "            %s: conv(&self.%s)?," % (snake(m.name), snake(m.name))
            )
        out += ["            ..Default::default()", "        })", "    }", "}", ""]
    for op in model.ops:
        name = ffi_args_name(op)
        out += ["#[repr(C)]", "pub struct %s {" % name]
        for a in op.args:
            out.append("    pub %s: %s," % (snake(a.name), a.type.ffi_rust()))
        out += ["}", ""]
    for op in model.ops:
        call_args = []
        for a in op.args:
            field = "args.%s" % snake(a.name)
            if (op.name, a.name) in RUST_BORROWED_ARGS:
                call_args.append("&conv::<Vec<_>, _>(&%s)?" % field)
            else:
                call_args.append("conv(&%s)?" % field)
        out += [
            "#[unsafe(no_mangle)]",
            'pub unsafe extern "C" fn %s(' % op.ffi_fn,
            "    builder: *mut WebnnGraphBuilder,",
            "    args: *const %s," % ffi_args_name(op),
            "    outputs: *mut u32,",
            "    outputs_capacity: usize,",
            "    outputs_len: *mut usize,",
            ") -> WebnnStatus {",
            "    unsafe {",
            "        add_operation(builder, args, outputs, outputs_capacity, outputs_len, |b, args| {",
            "            Ok(b.%s_with_options(%s)?.into())"
            % (op.rust_name, ", ".join(call_args)),
            "        })",
            "    }",
            "}",
            "",
        ]
    output.write("\n".join(out))
    return {webidl, __file__}


def mozinference_symbols(output, symbols, webidl):
    """Appends the per-operator engine functions to the symbols list."""
    from mozbuild.action.generate_symbols_file import generate_symbols_file

    model = Model(webidl)
    combined = output.name + ".in"
    with open(symbols, encoding="utf-8") as f:
        text = f.read()
    text += "#ifdef XP_MACOSX\n%s\n#endif\n" % "\n".join(op.ffi_fn for op in model.ops)
    with open(combined, "w", encoding="utf-8") as f:
        f.write(text)
    generate_symbols_file(output, combined)
    return {symbols, webidl, __file__}


