"""Generates the WebNN operator plumbing from dom/webidl/WebNN.webidl.

Every MLGraphBuilder method other than input(), constant() and build() is an
operator. For each one, this generates:
  - the IPDL op struct and the WebNNOperation union arm (checked in, because
    ipdl.py runs on a fixed list of source files, see `--check`),
  - the MLGraphBuilder method declaration and body (content process),
  - the declaration of its hand-written validator (WebNNValidation.h),
  - the conversion from the IPDL struct to the webnn_engine FFI and the call
    (HWInference process),
  - the webnn_engine FFI: #[repr(C)] structs, the extern "C" function calling
    rustnn, and the matching C declarations,
  - the list of exported engine symbols.

The build runs the functions taking an `output` file object (GENERATED_FILES).
Run `./mach python dom/webnn/codegen/webnn_codegen.py --check` to verify the
checked-in IPDL file, and `--write` to regenerate it.
"""

