# rustnn takes these MLGraphBuilder arguments as slices.
RUST_BORROWED_ARGS = {("slice", "starts"), ("slice", "sizes"), ("concat", "inputs")}
SNAKE_NAMES = {"isNaN": "is_nan"}
# rustnn has two split methods, one per union member, see ops.rs.
RUST_METHOD_NAMES = {"split": "split_union"}


def first_cap(name):
    return name[0].upper() + name[1:]


def snake(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.lower()


def strip_attrs(name):
    return name.replace("RangeEnforced", "").replace("Clamped", "")


class Type:
    """An IDL type, as used by an operator argument or dictionary member.

    kind is one of: operand, operands, uint32, int32, double, float, bool,
    string, enum, sequence, dictionary, union.
    """

    PRIMITIVES = {
        "uint32": ("uint32_t", "u32"),
        "int32": ("int32_t", "i32"),
        "double": ("double", "f64"),
        "float": ("float", "f32"),
        "bool": ("bool", "bool"),
    }

    def __init__(self, idl_type):
        t = idl_type
        self.idl = t
        self.inner = None
        self.name = None
        if t.isSequence():
            self.inner = Type(t.inner)
            if self.inner.kind == "operand":
                self.kind = "operands"
            else:
                assert (
                    self.inner.kind in self.PRIMITIVES or self.inner.kind == "enum"
                ), t
                self.kind = "sequence"
        elif t.isInterface():
            assert t.inner.identifier.name == "MLOperand", t
            self.kind = "operand"
        elif t.isEnum():
            self.kind = "enum"
            self.name = t.inner.identifier.name
        elif t.isDictionary():
            self.kind = "dictionary"
            self.name = t.inner.identifier.name
        elif t.isUnion():
            self.kind = "union"
            self.name = t.name
            self.members = [Type(m) for m in t.flatMemberTypes]
        elif t.isString():
            self.kind = "string"
        elif t.isPrimitive():
            tag = t.tag()
            tags = WebIDL.IDLType.Tags
            self.kind = {
                tags.uint32: "uint32",
                tags.int32: "int32",
                tags.double: "double",
                tags.unrestricted_double: "double",
                tags.float: "float",
                tags.unrestricted_float: "float",
                tags.bool: "bool",
            }[tag]
        else:
            raise Exception("Unsupported WebNN type %s" % t)

    # Name used for unions in IPDL and in the FFI.
    def union_name(self):
        return strip_attrs(self.name)

    def union_member_name(self):
        return strip_attrs(self.idl.name)

    def ipdl(self):
        if self.kind in ("operand",):
            return "uint32_t"
        if self.kind == "operands":
            return "uint32_t[]"
        if self.kind in self.PRIMITIVES:
            return self.PRIMITIVES[self.kind][0]
        if self.kind == "string":
            return "nsCString"
        if self.kind == "enum":
            return self.name
        if self.kind == "sequence":
            return self.inner.ipdl() + "[]"
        if self.kind == "dictionary":
            return ipdl_dict_name(self.name)
        if self.kind == "union":
            return "WebNN" + self.union_name()
        raise Exception(self.kind)

    def binding_param(self):
        """C++ type of a method argument, as the bindings pass it."""
        if self.kind == "operand":
            return "MLOperand&"
        if self.kind == "operands":
            return "const Sequence<OwningNonNull<MLOperand>>&"
        if self.kind in self.PRIMITIVES:
            return self.PRIMITIVES[self.kind][0]
        if self.kind == "enum":
            return self.name
        if self.kind == "sequence":
            return "const Sequence<%s>&" % self.inner.binding_param()
        if self.kind == "dictionary":
            return "const %s&" % self.name
        if self.kind == "union":
            return "const %s&" % self.name
        raise Exception(self.kind)

    def validator_param(self):
        if self.kind == "operand":
            return "const dom::MLOperand&"
        if self.kind == "operands":
            return "const dom::Sequence<OwningNonNull<dom::MLOperand>>&"
        if self.kind in self.PRIMITIVES:
            return self.PRIMITIVES[self.kind][0]
        if self.kind == "enum":
            return "dom::" + self.name
        if self.kind == "sequence":
            return "const dom::Sequence<%s>&" % self.inner.validator_param()
        if self.kind in ("dictionary", "union"):
            return "const dom::%s&" % self.name
        raise Exception(self.kind)

    def ffi_c(self, optional=False):
        """C type of the FFI representation."""
        if self.kind == "operand":
            return "WebnnOptionalOperand" if optional else "WebnnOperandId"
        if self.kind == "operands":
            return "WebnnOperandSlice"
        if self.kind in self.PRIMITIVES:
            return "WebnnOptionalF64" if optional else self.PRIMITIVES[self.kind][0]
        if self.kind == "string":
            return "WebnnStr"
        if self.kind == "enum":
            return ffi_enum_name(self.name)
        if self.kind == "sequence":
            return sequence_ffi_name(self.inner, optional)
        if self.kind == "dictionary":
            return ffi_dict_name(self.name)
        if self.kind == "union":
            return "Webnn" + self.union_name()
        raise Exception(self.kind)

    def ffi_rust(self, optional=False):
        if self.kind in self.PRIMITIVES and not optional:
            return self.PRIMITIVES[self.kind][1]
        return self.ffi_c(optional)


def sequence_ffi_name(inner, optional):
    if inner.kind == "enum":
        base = ffi_enum_name(inner.name) + "Slice"
    else:
        base = {"uint32": "WebnnU32Slice", "float": "WebnnF32Slice"}[inner.kind]
    if optional:
        base = base.replace("Webnn", "WebnnOptional", 1)
    return base


def ipdl_dict_name(name):
    assert name.startswith("ML")
    return "WebNN" + name[2:]


def ffi_dict_name(name):
    return "Webnn" + name


def ffi_enum_name(name):
    return "Webnn" + name


def ffi_args_name(op):
    return "Webnn%sArgs" % first_cap(op.name)


class Member:
    def __init__(self, member):
        self.name = member.identifier.name
        self.type = Type(member.type)
        # Optional<T> in the bindings, Maybe<T> in IPDL.
        self.optional = member.optional and member.defaultValue is None

    def ipdl(self):
        return self.type.ipdl() + ("?" if self.optional else "")


class Dictionary:
    def __init__(self, d):
        self.name = d.identifier.name
        self.members = []
        chain = []
        while d:
            chain.insert(0, d)
            d = d.parent
        for dd in chain:
            self.members.extend(Member(m) for m in dd.members)


class Arg:
    def __init__(self, arg):
        self.name = arg.identifier.name
        self.type = Type(arg.type)
        self.cpp_name = "a" + first_cap(self.name)


class Op:
    def __init__(self, method):
        self.name = method.identifier.name
        signatures = method.signatures()
        assert len(signatures) == 1, self.name
        ret, args = signatures[0]
        self.multi_output = ret.isSequence()
        self.args = [Arg(a) for a in args]
        assert self.args[-1].type.kind == "dictionary", self.name
        self.options = self.args[-1]
        self.native = first_cap(self.name)
        self.ipdl_struct = "WebNN%sOp" % self.native
        snake_name = SNAKE_NAMES.get(self.name, snake(self.name))
        self.rust_name = RUST_METHOD_NAMES.get(self.name, snake_name)
        self.ffi_fn = "webnn_graph_builder_%s" % snake_name

    def output_field(self):
        return "outputs" if self.multi_output else "output"


class Model:
    def __init__(self, webidl_path):
        # The parser writes a debug file to its output directory.
        with tempfile.TemporaryDirectory() as outputdir:
            parser = WebIDL.Parser(outputdir)
            parser.parse(PRELUDE, "prelude")
            with open(webidl_path, encoding="utf-8") as f:
                parser.parse(f.read(), webidl_path)
            results = parser.finish()
        builder = next(
            r
            for r in results
            if r.isInterface() and r.identifier.name == "MLGraphBuilder"
        )
        self.ops = [
            Op(m)
            for m in builder.members
            if m.isMethod() and m.identifier.name not in HAND_WRITTEN_METHODS
        ]
        dicts = {r.identifier.name: r for r in results if r.isDictionary()}
        self.enums = [r for r in results if r.isEnum()]
        self.dicts = []
        seen = set()
        unions = {}
        sequences = {}
        for op in self.ops:
            for arg in op.args:
                if arg.type.kind == "union":
                    unions[arg.type.union_name()] = arg.type
                if arg.type.kind == "dictionary" and arg.type.name not in seen:
                    seen.add(arg.type.name)
                    self.dicts.append(Dictionary(dicts[arg.type.name]))
        for d in self.dicts:
            for m in d.members:
                if m.type.kind == "sequence" and m.type.inner.kind == "enum":
                    sequences[m.type.inner.name] = m.type.inner
        self.unions = list(unions.values())
        self.enum_sequences = list(sequences.values())


def enum_variant(value):
    """C++ binding enumerator name of an IDL enum value, see Codegen.py."""
    if value == "":
        return "_empty"
    name = re.sub(r"[^0-9_a-zA-Z]", "_", value)
    return first_cap(name)


def rust_variant(value):
    return "".join(first_cap(p) for p in re.split(r"[^0-9a-zA-Z]", value) if p)


