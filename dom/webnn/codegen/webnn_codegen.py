def generate_ipdl(model):
    out = [
        "/* -*- Mode: C++; tab-width: 8; indent-tabs-mode: nil; c-basic-offset: 2 -*- */",
        MPL.rstrip(),
        "",
        "// " + HEADER_NOTE,
        "",
    ]
    for enum in model.enums:
        out.append(
            'using mozilla::dom::%s from "mozilla/webnn/WebNNIPCUtils.h";'
            % enum.identifier.name
        )
    out += ["", "namespace mozilla {", "namespace webnn {", ""]
    out += [
        "struct WebNNInputOp {",
        "  nsCString name;",
        "  uint32_t output;",
        "};",
        "",
        "// `constantIndex` indexes the constant buffers sent alongside the graph.",
        "struct WebNNConstantOp {",
        "  uint32_t constantIndex;",
        "  uint32_t output;",
        "};",
        "",
    ]
    for union in model.unions:
        out.append("union WebNN%s {" % union.union_name())
        for m in union.members:
            out.append("  %s;" % m.ipdl())
        out += ["};", ""]
    for d in model.dicts:
        out.append("struct %s {" % ipdl_dict_name(d.name))
        for m in d.members:
            out.append("  %s %s;" % (m.ipdl(), m.name))
        out += ["};", ""]
    for op in model.ops:
        out.append("struct %s {" % op.ipdl_struct)
        for arg in op.args:
            out.append("  %s %s;" % (arg.type.ipdl(), arg.name))
        if op.multi_output:
            out.append("  uint32_t[] outputs;")
        else:
            out.append("  uint32_t output;")
        out += ["};", ""]
    out.append("union WebNNOperation {")
    out.append("  WebNNInputOp;")
    out.append("  WebNNConstantOp;")
    for op in model.ops:
        out.append("  %s;" % op.ipdl_struct)
    out += ["};", "", "}  // namespace webnn", "}  // namespace mozilla", ""]
    return "\n".join(out)


