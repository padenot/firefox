def to_ffi_expr(t, expr, optional):
    """C++ expression converting an IPDL value to its FFI representation.

    `r` is the OperandResolver of the operation being converted."""
    if t.kind == "operand":
        return ("r.OptionalOperand(%s)" if optional else "r.Operand(%s)") % expr
    if t.kind == "operands":
        return "r.Operands(%s)" % expr
    if t.kind in Type.PRIMITIVES:
        return ("ToFfi(%s)" if optional else "%s") % expr
    if t.kind == "string":
        return "ToFfi(%s)" % expr
    if t.kind == "enum":
        return "static_cast<%s>(%s)" % (ffi_enum_name(t.name), expr)
    if t.kind == "sequence":
        if t.inner.kind == "enum":
            ty = sequence_ffi_name(t.inner, optional)
            return "r.Enums<%s>(%s)" % (ty, expr)
        return "ToFfi(%s)" % expr
    if t.kind in ("dictionary", "union"):
        return "ToFfi(r, %s)" % expr
    raise Exception(t.kind)


def parent_cpp(output, webidl):
    model = Model(webidl)
    out = [
        MPL,
        "// " + HEADER_NOTE,
        "",
        '#include "mozilla/webnn/WebNNParentOps.h"',
        "",
        '#include "mozilla/llama/LlamaRuntimeLinker.h"',
        "",
        "namespace mozilla::webnn {",
        "",
    ]
    for union in model.unions:
        ffi = "Webnn" + union.union_name()
        out.append(
            "static %s ToFfi(OperandResolver& r, const WebNN%s& aValue) {"
            % (ffi, union.union_name())
        )
        out.append("  %s result{};" % ffi)
        out.append("  switch (aValue.type()) {")
        for i, m in enumerate(union.members):
            arm = m.ipdl()
            arm_name = {"uint32_t": "uint32_t", "uint32_t[]": "ArrayOfuint32_t"}.get(
                arm
            )
            assert arm_name, arm
            out += [
                "    case WebNN%s::T%s:" % (union.union_name(), arm_name),
                "      result.tag = %d;" % i,
                "      result.%s = %s;"
                % (
                    snake(m.union_member_name()),
                    to_ffi_expr(m, "aValue.get_%s()" % arm_name, False),
                ),
                "      break;",
            ]
        out += ["    default:", "      r.Fail();", "  }", "  return result;", "}", ""]
    for d in model.dicts:
        ffi = ffi_dict_name(d.name)
        out.append(
            "static %s ToFfi([[maybe_unused]] OperandResolver& r, const %s& aValue) {"
            % (ffi, ipdl_dict_name(d.name))
        )
        out.append("  %s result{};" % ffi)
        for m in d.members:
            out.append(
                "  result.%s = %s;"
                % (
                    snake(m.name),
                    to_ffi_expr(m.type, "aValue.%s()" % m.name, m.optional),
                )
            )
        out += ["  return result;", "}", ""]
    out += [
        "AddOperationResult AddOperation(llama::LlamaLibWrapper* aLib,",
        "                                WebnnGraphBuilder* aBuilder,",
        "                                const WebNNOperation& aOperation,",
        "                                nsTArray<Maybe<uint32_t>>& aOperands) {",
        "  OperandResolver r(aOperands);",
        "  switch (aOperation.type()) {",
    ]
    for op in model.ops:
        out += [
            "    case WebNNOperation::T%s: {" % op.ipdl_struct,
            "      const %s& op = aOperation.get_%s();"
            % (op.ipdl_struct, op.ipdl_struct),
            "      %s args{};" % ffi_args_name(op),
        ]
        for arg in op.args:
            out.append(
                "      args.%s = %s;"
                % (snake(arg.name), to_ffi_expr(arg.type, "op.%s()" % arg.name, False))
            )
        if op.multi_output:
            out.append(
                "      return r.Call(aLib->%s, aBuilder, args, op.outputs());"
                % op.ffi_fn
            )
        else:
            out.append(
                "      return r.Call(aLib->%s, aBuilder, args, Span(&op.output(), 1));"
                % op.ffi_fn
            )
        out.append("    }")
    out += [
        "    default:",
        "      return AddOperationResult::Invalid;",
        "  }",
        "}",
        "",
        "}  // namespace mozilla::webnn",
        "",
    ]
    output.write("\n".join(out))
    return {webidl, __file__}


